async def seed_remaining() -> dict:
    target_langs = [l for l in ALL_LANGS if l != SOURCE_LANG]
    print(
        f"\n=== source_lang={SOURCE_LANG} (SADECE KALAN {len(REMAINING_CONCEPTS)} "
        f"kavram, 11 hedef dilin hepsinde tamamlanmamis olanlar) x "
        f"{len(target_langs)} hedef dil ===\n"
    )
    stats = {"eklendi": 0, "zaten_vardi": 0, "bulunamadi": 0}
    consecutive_not_found = 0

    for source_word, level in REMAINING_CONCEPTS:
        # 'en' zaten kaynak dil oldugu icin capa cevirisi gerekmiyor --
        # source_word kavramin kendisi.
        for target_lang in target_langs:
            outcome = await seed_target(SOURCE_LANG, source_word, level, target_lang)
            stats[outcome] += 1
            if outcome == "eklendi":
                print(f"  [EKLENDI] {source_word} ({SOURCE_LANG}->{target_lang}, {level})")
                consecutive_not_found = 0
            elif outcome == "bulunamadi":
                consecutive_not_found += 1
                print(f"  [BULUNAMADI] {source_word} ({SOURCE_LANG}->{target_lang})")
                if consecutive_not_found >= ANCHOR_FAILURE_CIRCUIT_BREAKER:
                    print(
                        f"\n  [DURDURULDU] {consecutive_not_found} sozluk sorgusu art arda "
                        f"sonuc bulamadi -- muhtemelen MyMemory API kota/rate-limit sorunu. "
                        f"Kalan kavramlar atlaniyor (hicbir sey uydurulmadi/yanlis yazilmadi -- "
                        f"sadece hic yazilmadi). Birkac saat ya da ertesi gun ayni komutla "
                        f"tekrar calistir, kaldigi yerden (zaten eklenenler atlanarak) guvenle "
                        f"devam eder.\n"
                    )
                    raise RateLimitSuspected(SOURCE_LANG)
            else:
                consecutive_not_found = 0
            await asyncio.sleep(REQUEST_DELAY_SECONDS)

    print(f"\n=== {SOURCE_LANG} (kalanlar) tamamlandi ===")
    print(stats)
    return stats


