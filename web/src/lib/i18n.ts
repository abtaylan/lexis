/**
 * lib/i18n.ts
 *
 * Uygulama arayüzü çeviri katmanı. Kullanıcının profildeki `native_lang`
 * alanına göre arayüz metinlerini (menü, başlıklar, butonlar, boş durum
 * mesajları) çevirir. Kapsam bilinçli olarak sınırlı tutuldu:
 *
 *  - Kapsamda: global chrome (Sidebar), Dashboard, Program (Çalışma
 *    Programı) sayfası, Profil sayfası, Login / Register sayfaları
 *    (kullanıcı henüz login olmadığı için `native_lang` yerine, elle
 *    seçilip localStorage'da tutulan bir "misafir arayüz dili" kullanılır
 *    — bkz. `useGuestUiLang()` / `LangSwitcher` bileşeni).
 *  - Kapsam DIŞI (henüz): Kelimeler / Flashcards / Quiz / İstatistik /
 *    Admin sayfaları.
 *  - Program şablonlarındaki aktivite adları (`Teknik Makale`,
 *    `Haber Okuma` vb.) kasıtlı olarak ÇEVRİLMEDİ — bunlar backend'e
 *    kaydedilen veri değerleri, UI metni değil. Bunun için zaten
 *    kalan-işler listesinde ayrı bir madde var: `activity_key` alanının
 *    dile bağımsız anahtar olarak kullanılması (seed_schedule.py).
 *
 * Yeni bir sayfayı çeviriye eklemek için: o sayfadaki sabit metinleri bu
 * dosyaya yeni anahtarlarla ekle, sonra sayfada `useT()` ile kullan.
 */

export type UiLang = 'tr' | 'en' | 'de' | 'fr' | 'es' | 'it' | 'ar' | 'ru' | 'ja';

export const SUPPORTED_UI_LANGS: UiLang[] = ['tr', 'en', 'de', 'fr', 'es', 'it', 'ar', 'ru', 'ja'];

export const RTL_UI_LANGS: UiLang[] = ['ar'];

export const DEFAULT_UI_LANG: UiLang = 'tr';

export function isUiLang(code?: string | null): code is UiLang {
  return !!code && (SUPPORTED_UI_LANGS as string[]).includes(code);
}

export function resolveUiLang(nativeLang?: string | null): UiLang {
  return isUiLang(nativeLang) ? nativeLang : DEFAULT_UI_LANG;
}

