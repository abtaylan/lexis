const DICTS: Record<UiLang, Dict> = { tr, en, de, fr, es, it, ar, ru, ja };

export function translate(lang: UiLang, key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[lang]?.[key] ?? DICTS.tr[key] ?? key;
  if (!vars) return raw;
  return Object.keys(vars).reduce(
    (acc, k) => acc.replaceAll(`{${k}}`, String(vars[k])),
    raw
  );
}

// ── React hook'ları ─────────────────────────────────────────────
// useAuth() burada import edilir; bu dosya 'use client' bileşenlerinden
// çağrılmalı (Sidebar, Dashboard, Schedule, Profile, (app)/layout.tsx hepsi
// zaten 'use client').
import { useAuth } from '@/store/auth';
import { useCallback, useMemo, useState, useEffect } from 'react';

// ── Misafir (login olmamış) kullanıcılar için arayüz dili ────────
// Login / Register sayfalarında `native_lang` henüz bilinmiyor, bu yüzden
// kullanıcının elle seçtiği dil localStorage'da tutulur ve aynı sekmedeki
// tüm bileşenlere bir CustomEvent ile yayılır (LangSwitcher bu event'i
// tetikler, useGuestUiLang onu dinler).
const GUEST_LANG_KEY = 'lexis_guest_ui_lang';
const GUEST_LANG_EVENT = 'lexis-guest-lang-change';

function detectBrowserUiLang(): UiLang {
  if (typeof navigator === 'undefined') return DEFAULT_UI_LANG;
  const candidates = [navigator.language, ...(navigator.languages || [])];
  for (const c of candidates) {
    const base = c?.split('-')[0]?.toLowerCase();
    if (isUiLang(base)) return base;
  }
  return DEFAULT_UI_LANG;
}

export function getGuestUiLang(): UiLang {
  if (typeof window === 'undefined') return DEFAULT_UI_LANG;
  const stored = window.localStorage.getItem(GUEST_LANG_KEY);
  return isUiLang(stored) ? stored : detectBrowserUiLang();
}

export function setGuestUiLang(lang: UiLang): void {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem(GUEST_LANG_KEY, lang);
  window.dispatchEvent(new CustomEvent<UiLang>(GUEST_LANG_EVENT, { detail: lang }));
}

/**
 * Misafir (login olmamış) kullanıcının elle seçtiği arayüz dilini okur/
 * günceller. Login/Register sayfalarında ve auth layout'ta kullanılır.
 */
export function useGuestUiLang(): [UiLang, (lang: UiLang) => void] {
  const [lang, setLang] = useState<UiLang>(DEFAULT_UI_LANG);

  useEffect(() => {
    setLang(getGuestUiLang());
    const handler = (e: Event) => {
      const detail = (e as CustomEvent<UiLang>).detail;
      if (isUiLang(detail)) setLang(detail);
    };
    window.addEventListener(GUEST_LANG_EVENT, handler);
    return () => window.removeEventListener(GUEST_LANG_EVENT, handler);
  }, []);

  const update = useCallback((l: UiLang) => {
    setGuestUiLang(l);
    setLang(l);
  }, []);

  return [lang, update];
}

/**
 * Oturum açmış kullanıcının native_lang alanına göre çözümlenmiş arayüz
 * dilini (ve RTL bilgisini) döndürür. Oturum yoksa (Login/Register gibi
 * misafir sayfalarda) elle seçilmiş misafir diline düşer.
 */
export function useUiLang(): { lang: UiLang; isRtl: boolean } {
  const { user, isAuthenticated } = useAuth();
  const [guestLang] = useGuestUiLang();
  const lang = useMemo(
    () => (isAuthenticated && user?.native_lang ? resolveUiLang(user.native_lang) : guestLang),
    [isAuthenticated, user?.native_lang, guestLang]
  );
  const isRtl = useMemo(() => (RTL_UI_LANGS as string[]).includes(lang), [lang]);
  return { lang, isRtl };
}

/**
 * Kullanıcının ana diline göre çeviri yapan `t(key, vars?)` fonksiyonunu
 * (ve çözümlenmiş dil/RTL bilgisini) döndürür. Bileşenlerde şöyle kullanılır:
 *
 *   const { t } = useT();
 *   <h1>{t('dashboard.greeting')}</h1>
 *   <p>{t('dashboard.streak', { n: streakCount })}</p>
 */
export function useT(): { t: (key: string, vars?: Record<string, string | number>) => string; lang: UiLang; isRtl: boolean } {
  const { lang, isRtl } = useUiLang();
  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang]
  );
  return { t, lang, isRtl };
}
